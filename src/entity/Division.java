package entity;

public class Division {

    private int id;
    private String divisionName;

    public Division(){}

    public int getId(){
        return id;
    }

    public void setId(int id){
        this.id=id;
    }

    public String getDivisionName(){
        return divisionName;
    }

    public void setDivisionName(String divisionName){
        this.divisionName=divisionName;
    }

}